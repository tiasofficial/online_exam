async function verifyAndReport() {
  const total = await questionBankModel.countDocuments({});
  const distinct = (await questionBankModel.distinct('body')).length;
  console.log(`Current state: Total Questions = ${total}, Distinct Question Bodies = ${distinct}`);
  if (total === distinct) {
    console.log('✅ ALL QUESTIONS IN DATABASE ARE 100% UNIQUE. ZERO DUPLICATES EXIST.');
  } else {
    console.log(`⚠️ Detected ${total - distinct} duplicates. Removing them now...`);
    const uniqueDocs = await questionBankModel.aggregate([
      { $group: { _id: "$body", docId: { $first: "$_id" } } }
    ]);
    const uniqueIds = uniqueDocs.map(d => d.docId);
    await questionBankModel.deleteMany({ _id: { $nin: uniqueIds } });
    console.log('✅ All repetitive duplicates deleted!');
  }
  process.exit(0);
}

verifyAndReport();
